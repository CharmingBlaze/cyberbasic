// AST -> JavaScript. The program becomes a generator so `Sync` can hand control back to the
// browser each frame (PLAN.md §4.3).
// shortcut: emits JS straight from the AST; the shared IR (PLAN.md §7) goes in between once graphs compile too.
// shortcut: a While loop with no Sync freezes the tab; add the loop guard from §4.3 with the debugger hooks.

use crate::parser::{Expr, Kind, Stmt};
use std::collections::BTreeSet;
use std::fmt::Write;

pub fn generate(prog: &[Stmt]) -> String {
    let mut vars = BTreeSet::new();
    prog.iter().for_each(|s| collect_stmt(s, &mut vars));
    let mut out = String::from("// Generated by cyberbasic. Do not edit.\nCB.run(function* () {\n");
    if !vars.is_empty() {
        let decl: Vec<String> = vars.iter().map(|v| format!("v_{v} = 0")).collect();
        writeln!(out, "  let {};", decl.join(", ")).unwrap();
    }
    block(&mut out, prog, 1);
    out.push_str("});\n");
    out
}

fn block(out: &mut String, stmts: &[Stmt], depth: usize) {
    for s in stmts {
        stmt(out, s, depth);
    }
}

fn stmt(out: &mut String, s: &Stmt, depth: usize) {
    let pad = "  ".repeat(depth);
    // CB.ln lets runtime errors report the BASIC line; seed of the debugger hooks in §7.3.
    write!(out, "{pad}CB.ln = {}; ", s.line).unwrap();
    match &s.kind {
        Kind::Assign(t, op, v) => writeln!(out, "{} {op} {};", expr(t), expr(v)).unwrap(),
        Kind::Cmd(name, args) => writeln!(out, "CB.{name}({});", list(args)).unwrap(),
        Kind::Sync => out.push_str("yield;\n"),
        Kind::End => out.push_str("return;\n"),
        Kind::While(c, body) => {
            writeln!(out, "while ({}) {{", expr(c)).unwrap();
            block(out, body, depth + 1);
            writeln!(out, "{pad}}}").unwrap();
        }
        Kind::If(c, then, els) => {
            writeln!(out, "if ({}) {{", expr(c)).unwrap();
            block(out, then, depth + 1);
            if !els.is_empty() {
                writeln!(out, "{pad}}} else {{").unwrap();
                block(out, els, depth + 1);
            }
            writeln!(out, "{pad}}}").unwrap();
        }
    }
}

fn list(args: &[Expr]) -> String {
    args.iter().map(expr).collect::<Vec<_>>().join(", ")
}

fn expr(e: &Expr) -> String {
    match e {
        Expr::Num(n) => n.clone(),
        Expr::Str(s) => format!("{s:?}"),
        Expr::Var(v) => format!("v_{v}"), // prefix keeps BASIC names clear of JS reserved words
        Expr::Const(c) => format!("CB.{c}"),
        Expr::Delta => "CB.delta".into(),
        Expr::Call(name, args) => format!("CB.{name}({})", list(args)),
        Expr::Field(o, f) => format!("{}.{f}", expr(o)),
        Expr::Neg(x) => format!("(-{})", expr(x)),
        Expr::Not(x) => format!("(!{})", expr(x)),
        Expr::Bin(op, l, r) => format!("({} {op} {})", expr(l), expr(r)),
    }
}

fn collect_stmt(s: &Stmt, vars: &mut BTreeSet<String>) {
    match &s.kind {
        Kind::Assign(t, _, v) => {
            collect_expr(t, vars);
            collect_expr(v, vars);
        }
        Kind::Cmd(_, args) => args.iter().for_each(|a| collect_expr(a, vars)),
        Kind::While(c, body) => {
            collect_expr(c, vars);
            body.iter().for_each(|s| collect_stmt(s, vars));
        }
        Kind::If(c, then, els) => {
            collect_expr(c, vars);
            then.iter().chain(els).for_each(|s| collect_stmt(s, vars));
        }
        Kind::Sync | Kind::End => {}
    }
}

fn collect_expr(e: &Expr, vars: &mut BTreeSet<String>) {
    match e {
        Expr::Var(v) => {
            vars.insert(v.clone());
        }
        Expr::Call(_, args) => args.iter().for_each(|a| collect_expr(a, vars)),
        Expr::Field(x, _) | Expr::Neg(x) | Expr::Not(x) => collect_expr(x, vars),
        Expr::Bin(_, l, r) => {
            collect_expr(l, vars);
            collect_expr(r, vars);
        }
        Expr::Num(_) | Expr::Str(_) | Expr::Const(_) | Expr::Delta => {}
    }
}
