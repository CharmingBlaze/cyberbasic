// AST -> JavaScript. The program and every user function become generators so `Sync`, `Delay`
// and loading can hand control back to the browser each frame (PLAN.md §4.3).
// shortcut: emits JS straight from the AST; the shared IR (PLAN.md §7) goes in between once graphs compile too.

use crate::parser::{Expr, Kind, Program, Stmt};
use std::collections::BTreeSet;
use std::fmt::Write;

struct Gen<'a> {
    out: String,
    globals: &'a BTreeSet<String>,
    params: BTreeSet<String>,
    in_func: bool,
    /// Debug builds pause at breakpoints and report variables (PLAN.md §7.3).
    debug: bool,
    /// Function name for the debugger, and a JS expression snapshotting every variable in
    /// scope (BASIC name -> value).
    func: String,
    scope: String,
}

pub fn generate(p: &Program, debug: bool) -> String {
    let mut g = Gen {
        out: String::new(),
        globals: &p.globals,
        params: BTreeSet::new(),
        in_func: false,
        debug,
        func: String::new(),
        scope: String::new(),
    };
    g.out.push_str("// Generated by cyberbasic. Do not edit.\n(() => {\n\"use strict\";\n");
    if !p.globals.is_empty() {
        let decl: Vec<String> = p.globals.iter().map(|v| format!("g_{v} = 0")).collect();
        writeln!(g.out, "let {};", decl.join(", ")).unwrap();
    }
    for t in &p.types {
        let fields: Vec<String> = t.fields.iter().map(|f| format!("{f:?}")).collect();
        writeln!(g.out, "const T_{} = [{}];", t.name, fields.join(", ")).unwrap();
    }
    for f in &p.funcs {
        g.params = f.params.iter().cloned().collect();
        g.in_func = true;
        g.func = f.name.clone();
        let params: Vec<String> = f.params.iter().map(|p| format!("v_{p}")).collect();
        writeln!(g.out, "function* f_{}({}) {{", f.name, params.join(", ")).unwrap();
        g.locals(&f.body);
        g.block(&f.body, 1);
        g.out.push_str("  return 0;\n}\n");
    }
    g.params.clear();
    g.in_func = false;
    g.func = "main".into();
    g.out.push_str("CB.run(function* () {\n");
    g.locals(&p.main);
    g.block(&p.main, 1);
    g.out.push_str("});\n})();\n");
    g.out
}

impl Gen<'_> {
    fn var(&self, v: &str) -> String {
        if !self.params.contains(v) && self.globals.contains(v) {
            format!("g_{v}")
        } else {
            format!("v_{v}") // prefix keeps BASIC names clear of JS reserved words
        }
    }

    /// Declares every variable a body uses that isn't a parameter or global. Like Blitz, an
    /// undeclared variable is local and starts at 0.
    fn locals(&mut self, body: &[Stmt]) {
        let mut vars = BTreeSet::new();
        body.iter().for_each(|s| collect_stmt(s, &mut vars));
        let all: BTreeSet<&String> = vars.iter().chain(&self.params).chain(self.globals).collect();
        let snapshot: Vec<String> = all.iter().map(|v| format!("{v}: {}", self.var(v))).collect();
        self.scope = format!("{{ {} }}", snapshot.join(", "));
        let decl: Vec<String> = vars
            .iter()
            .filter(|v| !self.params.contains(*v) && !self.globals.contains(*v))
            .map(|v| format!("v_{v} = 0"))
            .collect();
        if !decl.is_empty() {
            writeln!(self.out, "  let {};", decl.join(", ")).unwrap();
        }
    }

    fn block(&mut self, stmts: &[Stmt], depth: usize) {
        for s in stmts {
            self.stmt(s, depth);
        }
    }

    fn stmt(&mut self, s: &Stmt, depth: usize) {
        let pad = "  ".repeat(depth);
        if let Kind::Nop = s.kind {
            return;
        }
        if let Kind::Seq(stmts) = &s.kind {
            return self.block(stmts, depth);
        }
        // CB.ln lets runtime errors report the BASIC line; seed of the debugger hooks in §7.3.
        write!(self.out, "{pad}CB.ln = {}; ", s.line).unwrap();
        if self.debug {
            // CB.trap is false unless breakpoints, stepping or a pause request exist: near-free otherwise.
            write!(self.out, "if (CB.trap) yield* CB.pause({}, {:?}, () => ({})); ", s.line, self.func, self.scope).unwrap();
        }
        match &s.kind {
            Kind::Assign(Expr::Index(base, idx), op, v) => {
                let (b, i, v) = (self.expr(base), self.expr(idx), self.expr(v));
                writeln!(self.out, "{{ const $a = {b}, $i = CB.ck($a, {i}); $a[$i] {op} {v}; }}").unwrap();
            }
            Kind::Assign(t, op, v) => {
                let (t, v) = (self.expr(t), self.expr(v));
                writeln!(self.out, "{t} {op} {v};").unwrap();
            }
            Kind::Cmd(b, args) => {
                let call = format!("CB.{}({})", b.name, self.list(args));
                let y = if b.wait { "yield* " } else { "" };
                writeln!(self.out, "{y}{call};").unwrap();
            }
            Kind::UserCall(name, args) => {
                let args = self.list(args);
                writeln!(self.out, "yield* f_{name}({args});").unwrap();
            }
            Kind::Sync => self.out.push_str("yield;\n"),
            Kind::End => self.out.push_str("throw CB.END;\n"),
            Kind::Exit => self.out.push_str("break;\n"),
            Kind::Return(e) => {
                let v = match (e, self.in_func) {
                    (Some(e), true) => format!(" {}", self.expr(e)),
                    (None, true) => " 0".into(),
                    _ => String::new(),
                };
                writeln!(self.out, "return{v};").unwrap();
            }
            Kind::Dim(v, dims) => {
                let (v, d) = (self.var(v), self.list(dims));
                writeln!(self.out, "{v} = CB.dim({d});").unwrap();
            }
            Kind::Delete(e) => {
                let e = self.expr(e);
                writeln!(self.out, "CB.del({e});").unwrap();
            }
            Kind::While(c, body) => {
                let c = self.expr(c);
                writeln!(self.out, "while ({c}) {{ CB.guard();").unwrap();
                self.close(body, depth);
            }
            Kind::Repeat(body, until) => {
                match until {
                    Some(_) => self.out.push_str("do { CB.guard();\n"),
                    None => self.out.push_str("while (true) { CB.guard();\n"),
                }
                self.block(body, depth + 1);
                match until {
                    Some(c) => {
                        let c = self.expr(c);
                        writeln!(self.out, "{pad}}} while (!({c}));").unwrap();
                    }
                    None => writeln!(self.out, "{pad}}}").unwrap(),
                }
            }
            Kind::For { var, from, to, step, body } => {
                let v = self.var(var);
                let (from, to) = (self.expr(from), self.expr(to));
                let step = step.as_ref().map_or("1".into(), |s| self.expr(s));
                writeln!(
                    self.out,
                    "{{ const $e = {to}, $s = {step}; for ({v} = {from}; $s >= 0 ? {v} <= $e : {v} >= $e; {v} += $s) {{ CB.guard();"
                )
                .unwrap();
                self.block(body, depth + 1);
                writeln!(self.out, "{pad}}} }}").unwrap();
            }
            Kind::ForEach { var, ty, body } => {
                let v = self.var(var);
                writeln!(self.out, "for ({v} of CB.each(T_{ty})) {{ if ({v}.$dead) continue; CB.guard();").unwrap();
                self.close(body, depth);
            }
            Kind::If(c, then, els) => {
                let c = self.expr(c);
                writeln!(self.out, "if ({c}) {{").unwrap();
                self.block(then, depth + 1);
                if !els.is_empty() {
                    writeln!(self.out, "{pad}}} else {{").unwrap();
                    self.block(els, depth + 1);
                }
                writeln!(self.out, "{pad}}}").unwrap();
            }
            Kind::Select(subject, cases, default) => {
                let subject = self.expr(subject);
                write!(self.out, "{{ const $v = {subject};").unwrap();
                for (i, (vals, body)) in cases.iter().enumerate() {
                    let conds: Vec<String> = vals.iter().map(|v| format!("$v === {}", self.expr(v))).collect();
                    let kw = if i == 0 { " if" } else { " else if" };
                    writeln!(self.out, "{kw} ({}) {{", conds.join(" || ")).unwrap();
                    self.block(body, depth + 1);
                    write!(self.out, "{pad}}}").unwrap();
                }
                if !default.is_empty() {
                    let kw = if cases.is_empty() { " {" } else { " else {" };
                    writeln!(self.out, "{kw}").unwrap();
                    self.block(default, depth + 1);
                    write!(self.out, "{pad}}}").unwrap();
                }
                self.out.push_str(" }\n");
            }
            Kind::Seq(_) | Kind::Nop => unreachable!("handled above"),
        }
    }

    fn close(&mut self, body: &[Stmt], depth: usize) {
        self.block(body, depth + 1);
        writeln!(self.out, "{}}}", "  ".repeat(depth)).unwrap();
    }

    fn list(&self, args: &[Expr]) -> String {
        args.iter().map(|a| self.expr(a)).collect::<Vec<_>>().join(", ")
    }

    fn expr(&self, e: &Expr) -> String {
        match e {
            Expr::Num(n) => n.clone(),
            Expr::Str(s) => format!("{s:?}"),
            Expr::Var(v) => self.var(v),
            Expr::Const(c) => format!("CB.{c}"),
            Expr::Delta => "CB.delta".into(),
            Expr::Call(b, args) if b.wait => format!("(yield* CB.{}({}))", b.name, self.list(args)),
            Expr::Call(b, args) => format!("CB.{}({})", b.name, self.list(args)),
            Expr::UserCall(name, args) => format!("(yield* f_{name}({}))", self.list(args)),
            Expr::New(t) => format!("CB.newT(T_{t})"),
            Expr::Field(o, f) => format!("{}.{f}", self.expr(o)),
            Expr::Index(b, i) => format!("CB.ix({}, {})", self.expr(b), self.expr(i)),
            Expr::Neg(x) => format!("(-{})", self.expr(x)),
            Expr::Not(x) => format!("(!{})", self.expr(x)),
            Expr::Bin(op, l, r) => format!("({} {op} {})", self.expr(l), self.expr(r)),
        }
    }
}

fn collect_stmt(s: &Stmt, vars: &mut BTreeSet<String>) {
    let body = |b: &[Stmt], vars: &mut BTreeSet<String>| b.iter().for_each(|s| collect_stmt(s, vars));
    match &s.kind {
        Kind::Assign(t, _, v) => {
            collect_expr(t, vars);
            collect_expr(v, vars);
        }
        Kind::Cmd(_, args) | Kind::UserCall(_, args) => args.iter().for_each(|a| collect_expr(a, vars)),
        Kind::While(c, b) => {
            collect_expr(c, vars);
            body(b, vars);
        }
        Kind::Repeat(b, c) => {
            body(b, vars);
            c.iter().for_each(|c| collect_expr(c, vars));
        }
        Kind::For { var, from, to, step, body: b } => {
            vars.insert(var.clone());
            [from, to].into_iter().chain(step).for_each(|e| collect_expr(e, vars));
            body(b, vars);
        }
        Kind::ForEach { var, body: b, .. } => {
            vars.insert(var.clone());
            body(b, vars);
        }
        Kind::If(c, t, e) => {
            collect_expr(c, vars);
            body(t, vars);
            body(e, vars);
        }
        Kind::Select(subject, cases, default) => {
            collect_expr(subject, vars);
            for (vals, b) in cases {
                vals.iter().for_each(|v| collect_expr(v, vars));
                body(b, vars);
            }
            body(default, vars);
        }
        Kind::Dim(v, dims) => {
            vars.insert(v.clone());
            dims.iter().for_each(|d| collect_expr(d, vars));
        }
        Kind::Delete(e) | Kind::Return(Some(e)) => collect_expr(e, vars),
        Kind::Seq(b) => body(b, vars),
        Kind::Return(None) | Kind::Exit | Kind::Sync | Kind::End | Kind::Nop => {}
    }
}

fn collect_expr(e: &Expr, vars: &mut BTreeSet<String>) {
    match e {
        Expr::Var(v) => {
            vars.insert(v.clone());
        }
        Expr::Call(_, args) | Expr::UserCall(_, args) => args.iter().for_each(|a| collect_expr(a, vars)),
        Expr::Field(x, _) | Expr::Neg(x) | Expr::Not(x) => collect_expr(x, vars),
        Expr::Bin(_, l, r) | Expr::Index(l, r) => {
            collect_expr(l, vars);
            collect_expr(r, vars);
        }
        Expr::Num(_) | Expr::Str(_) | Expr::Const(_) | Expr::Delta | Expr::New(_) => {}
    }
}
